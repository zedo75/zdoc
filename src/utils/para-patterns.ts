// ==================== 标题与结构 ====================

// 注意：同段内有多个需要匹配的才加 g 标志
/**
 * 抬头（主送机关）。
 *
 * 冒号前排除书名号、六角括号与冒号本身——它们出现在抬头上方通常是
 * 发文事由（转发文件、引用文号），不应被识别为抬头。
 * 例：「各市、县（区）人民政府：」命中；「关于转发《…》〔…〕…：」不命中。
 */
export const SALUTATION_REGEX = /^[^《》〔〕：]*：\r$/;

/**
 * 一级标题：一、二、……。
 *
 * - 开头 `(?![\s\S]*[；;]\r?$)` 排除“整段以分号结尾”的并列列表项；
 * - 结尾 `[^；;]\r` 表示以段尾结束且末字不是分号。
 *
 * 只靠结尾分支不够：`一、甲事项。乙事项；` 会先命中中间的 `。`，
 * 所以必须整段检查是否以分号结尾。
 */
export const H1_REGEX = /^(?![\s\S]*[；;]\r?$)[一二三四五六七八九十]+、.*?(?:。|[^；;]\r)/;

/**
 * 二级标题：（一）（二）……。
 *
 * 结尾约定同 H1_REGEX（分号结尾不视为标题）。
 */
export const H2_REGEX = /^(?![\s\S]*[；;]\r?$)（[一二三四五六七八九十]+）.*?(?:。|[^；;]\r)/;

/**
 * - `(?!.*：)` 为先行断言，见以下链接
 * @see https://mdn.org.cn/en-US/docs/Web/JavaScript/Reference/Regular_expressions/Lookahead_assertion
 */
/*
export const H3_REGEX = /^(?!.*(?:：|\u2005))[0-9]{1,2}\..{1,23}?(?:。|[^；;]\r)/;
*/
/**
 * 三级标题：1.2.……。
 *
 * - `(?![\s\S]*[；;]\r?$)` 排除以分号结尾的段落（同 H1/H2）；
 * - 前缀 `[0-9]{1,2}\.` 是数字编号，紧跟 `(?!\d)` 排除小数、百分比、多级版本号
 *   （如 `1.5亿元`、`50.5%`、`2.5.1`），它们不是编号；
 * - 中段 `[^：\u2005\r]{1,23}?` 是 "标题正文"，**不允许含冒号、1/4间距（\u2005）**——
 *   因为 "标题：说明" 这种格式（如"联系人：张三"）不是三级标题；
 *   \u2005 是排版带序号的附件时使用的间距，也不应该视为三级标题；
 * - 结尾 `(?:。|[^；;]\r)` 要求以句号或段尾结束。
 *
 * **关键**：冒号的排除只作用于 "标题部分"（数字. 到第一个句号之间），不作用于整段。
 * 这样 "1.会议签到。签到地点：活动中心一楼" 这类 "标题 + 说明" 合段的写法能被正确识别为 h3。
 *
 * - `23` 为一行能容纳的字数：28 - 2（首缩）- 2（"00." 占宽）- 1（考虑标点压缩）
 * - 一二级标题暂不考虑限制 23 字，因为有的材料中会超过一行
 */
export const H3_REGEX =
    /^(?![\s\S]*[；;]\r?$)[0-9]{1,2}\.(?!\d)[^：\u2005\r]{1,23}?(?:。|[^；;]\r)/;

/**
 * 段内小标题：一是…。 / 二要…。
 * - 后行断言 (?<=^|[。；？！])：要求前面是段首或句末标点（含分号），
 *   避免从句子中间截；
 * - 终止符 `。` 或 `；`：条目之间常用分号断开（「一是…；二是…；三是…。」），
 *   只认句号会把整串当成一条，后面的条目得不到处理；
 * - 非贪婪 .*?：匹配到第一个句号 / 分号即止；
 * - 带 g，调用前需重置 lastIndex。
 */
export const TOPIC_REGEX = /(?<=^|[。；？！])[一二三四五六七八九十][是要].*?[。；]/g;

/** 段内小标题前缀：一是 / 二是 / … / 十是，或一要 / 二要 / … / 十要。 */
export const TOPIC_PREFIX_REGEX = /^[一二三四五六七八九十][是要]/;

// ==================== 列表项前缀 ====================

/**
 * 阿拉伯数字 + 半角点：`1.`、`12.`
 *
 * `(?!\d)` 排除小数点（`1.5`）——小数点后紧跟数字，不是列表编号。
 */
export const LIST_ITEM_NUMERIC_REGEX = /^[0-9]{1,2}\.(?!\d)/;
/** 全角括号 + 汉字数字：`（一）`、`（十二）` */
export const LIST_ITEM_PAREN_HAN_REGEX = /^（[一二三四五六七八九十]+）/;
/** 全角括号 + 阿拉伯数字：`（1）`、`（12）` */
export const LIST_ITEM_PAREN_NUM_REGEX = /^（[0-9]{1,2}）/;

/**
 * 主标题中禁止出现的符号。
 *
 * 包括句末标点（。；！？）和常见装饰符——它们出现在主标题块内，
 * 通常说明该行实为正文，不应被提升为标题。
 */
export const MAIN_TITLE_FORBIDDEN_SYMBOLS_REGEX = /[。；！？【】〖〗_=|{}<>#&~$^*※\[\]\\]/;

// ==================== 版头（红头） ====================

/**
 * 公文文种（标题结尾常见）。
 *
 * 用于区分「标题」与「版头」：标题以文种收尾，版头以发文机关名称收尾。
 * 末尾允许再跟一个括号说明（如「（送审稿）」）。
 */
export const DOC_TITLE_KIND_REGEX =
    /(?:通知|通报|报告|请示|批复|意见|决定|决议|命令|函|纪要|公告|通告|方案|办法|规定|细则|规划|计划|要点|总结|讲话|致辞|汇报|说明|答复|建议|议案|条例|准则|规则|简报)(?:（[^（）]*）)?$/;

/**
 * 发文机关名称的常见结尾。
 *
 * 命中说明整段更像「发文机关标志」而不是标题；不追求穷举，
 * 真正的把关靠「标题必须以文种收尾」与「版头后必须跟标题」两条互补规则。
 */
export const LETTERHEAD_ORG_TAIL_REGEX =
    /(?:文件|委员会|党委|党组|办公室|办公厅|人民政府|政府|法院|检察院|领导小组|联席会议|指挥部|工作室|中心|集团|公司|学校|学院|医院|协会|联合会|银行|分局|派出所|支队|大队|总队|局|厅|署|院|部|委|会|处|科|股|站|所|室)$/;

/**
 * 版头合并文本中不允许出现的词与标点。
 *
 * - 事由词（关于 / 转发 / 印发）：出现即说明这段是标题或正文；
 * - 句读与书名号 / 六角括号：发文机关名称里不会出现，标题与正文里常见。
 */
export const LETTERHEAD_FORBIDDEN_REGEX = /关于|转发|印发|[。；！？，、：]|[《》〔〕]/;

// ==================== 副标题相关 ====================

/** 副标题：整行被一对全角圆括号包裹，且括号内非空、无嵌套 */
export const SUBTITLE_PAREN_REGEX = /^（[^（）]+）$/;

/** 纯序号括号（一）（二）（1）（2）……；用于从 SUBTITLE_PAREN_REGEX 中剔除 */
export const SUBTITLE_PAREN_ORDINAL_REGEX = /^（[0-9一二三四五六七八九十]+）$/;

/** 副标题：括号内含"稿/案"，如（送审稿）、（征求意见稿） */
export const SUBTITLE_DRAFT_REGEX = /^（[^）]*[稿案][^）]*）$/;

/**
 * 段内任意位置的「（送审稿）/（草案）」括号。
 *
 * 与 `SUBTITLE_DRAFT_REGEX`（整行括号）不同：这里匹配句子中间的括号说明，
 * 如「审议《XX工作规则（送审稿）》」。出现在 h2 候选中通常说明这是
 * “审议某文件”的列表项，而不是小节标题。
 */
export const INLINE_DRAFT_PAREN_REGEX = /（[^（）]*[稿案][^（）]*）/;

/** 副标题：带括号的公文文号，如（某委〔2026〕1号） */
export const SUBTITLE_DOC_NUMBER_REGEX = /^（[^\s]{2,6}\u3014\d{4}\u3015\d+号）$/;

/** 副标题：括号日期，支持大小写 X / 全半角空格占位，如（2024年X月X日） */
export const SUBTITLE_BRACKET_DATE_REGEX =
    /^（[0-9xX]{4}年[0-9xX \u3000]{1,2}月[0-9xX \u3000]{1,2}日）$/;

/**
 * 普通姓名：末尾 2+ 半角空格 或 1+ 全角空格 后跟 2–4 汉字，字间可含空格
 * （兼容「李  四」）。
 *
 * 捕获组：`[1]` 职务部分、`[2]` 姓名部分（调用方用于姓氏校验）。
 */
export const PLAIN_NAME_REGEX =
    /^(.+?)(?: {2,}|\u3000+)([\u4e00-\u9fa5](?:[ \u3000]*[\u4e00-\u9fa5]){1,3})$/;

/**
 * 少数民族姓名：末尾 2+ 半角空格 或 1+ 全角空格 后跟含「·」的姓名，
 * 1–2 个「·」，每段 1–8 汉字。
 *
 * 捕获组：`[1]` 职务部分、`[2]` 姓名部分。
 */
export const ETHNIC_NAME_REGEX =
    /^(.+?)(?: {2,}|\u3000+)([\u4e00-\u9fa5]{1,8}(?:\u00B7[\u4e00-\u9fa5]{1,8}){1,2})$/;

// ==================== 附件相关 ====================

/** 单个附件行的 WPS 查找模式：分页符 + "附件X" + 段落标记 */
export const ATTACHMENT_WILDCARDS_PATTERN = "^m附件[0-9]{1,}^p";

/**
 * 附件说明块（`附件：1. … 2. …`）：
 *
 * - 可选缩进 + "附件[:：]" + 捕获正文，至连续两个换行 / 换页符 / 字符串末尾为止。
 * - 带 g，调用前需重置 lastIndex。
 */
export const ATTACHMENT_LIST_REGEX = /[ \u3000]*附件[：:]\s*([\s\S]+?)(?=[\r\n]{2}|\f|$)/g;

/** 附件说明块结尾的 WPS 查找模式：定位 "附件：…" 后跟两个段落标记的位置 */
export const ATTACHMENT_LIST_WILDCARDS_PATTERN = "附件[:：]*^p^p";

/** 附件段落前缀：附件 1 / 附件2 等
 *
 * （注意：与 ATTACHMENT_LIST_REGEX 的"附件：目录"不同）
 *
 * 编号后必须是空白、冒号或段尾，避免把正文引用
 * 「附件1和附件2的具体内容……」误判为附件标题行。
 */
export const ATTACHMENT_LINE_PREFIX_REGEX = /^附件\s*[0-9]+(?:\s|$|[：:])/;

// ==================== 抬头相关 ====================

/**
 * 抬头黑名单：任一命中即排除。
 *
 * 含两类：
 * - 套话词（贯彻、落实、关于、根据、如下、以下、下列、包括）——正文常见；
 * - 句号——句末标点出现在抬头里说明是正文句子而非抬头。
 */
export const SALUTATION_EXCLUDE_REGEX = /贯彻|落实|关于|根据|如下|以下|下列|包括|。/;

/** 抬头白名单（词级匹配） */
export const SALUTATION_ORG_DEPT_REGEX =
    /省|自治区|市|县|乡|镇|村|社区|委.*?(?:部|办)|局|工会|妇联|企业|党组织|大学/;

/** 抬头白名单：「各单位」「各部门」等概称 */
export const SALUTATION_EACH_UNIT_REGEX = /各.*?(?:单位|部门)/;

/** 抬头白名单：敬语、称呼 */
export const SALUTATION_GREETING_REGEX = /尊敬的|敬爱的|亲爱的|同志们/;

/**
 * 抬头白名单：职务名称（含 "副" 前缀）
 *
 * 常见于讲话稿、会议材料、党委内部行文等
 */
export const SALUTATION_JOB_TITLE_REGEX = /副?书记|副?主任|副?参谋长|副?政委/;

// ==================== 落款 ====================

/**
 * 落款成文日期。
 *
 * - 年、月、日都可用大小写 "X" 占位，月、日之前可用全/半角空格占位；
 * - 允许段首段尾空白（部分场景下 Range.Text 带缩进空格）。
 */
export const SIGNATURE_DATE_REGEX =
    /^\s*[0-9xX]{4}年[0-9xX \u3000]{1,2}月[0-9xX \u3000]{1,2}日\s*\r?$/;
